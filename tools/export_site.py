"""Build a training ground from a site-layout/1 document and export it as one .glb.

The site is generated by kit.site (plain Python, in parity with the Rust editor), realised in
Blender (kit/assets/site.py) and exported. With --game, materials are baked to game PBR (each
pitch's turf, lawns as tileable sets, recoloured library materials), props ship as one node per
asset with EXT_mesh_gpu_instancing arrays (position, yaw then tilt, scale, _SEAT_COLOR for
recolourable assets) and MSFT_lod links to their coarse levels.

blender -b -P tools/export_site.py -- layouts/training_superclub.json [--game]
"""
import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import bpy  # noqa: E402

from kit.assets import site as SITE  # noqa: E402
from kit.core.gltf_instancing import add_instances, add_lods  # noqa: E402
from kit.core.scene import OUT, reset  # noqa: E402
from kit.site import site as S  # noqa: E402


def main(path, game=False):
    t = time.time()
    reset()
    layout = json.loads(path.read_text())
    site = S.build(layout, S.load_catalog())
    for w in site.report.warnings:
        print(f"[site] warning: {w}", flush=True)
    root, info = SITE.realize(site, instanced=game)
    if game:
        from kit.core import game as GAME
        for o in list(bpy.data.objects):          # hero-only geometry: nets ship as their LOD1 cards
            if o.get("lod") == 0 and o.get("has_lod1"):
                bpy.data.objects.remove(o)
        GAME.prepare(None, pitches=info["pitches"], extra_tileable=info["materials"].lawns)
        info["materials"].apply_tints()
        GAME.area_lights_to_spots()
    out = OUT / "sites" / f"{path.stem}{'.game' if game else ''}.glb"
    out.parent.mkdir(parents=True, exist_ok=True)
    bpy.ops.export_scene.gltf(filepath=str(out), export_format="GLB", export_extras=True, export_yup=True,
                              export_apply=True, export_lights=True, export_vertex_color="ACTIVE")
    n = 0
    if game and info["instances"]:
        n = add_instances(out, info["instances"])
        if info["lods"]:
            add_lods(out, info["lods"])
    r = site.report
    print(f"[export] {out.name}: {out.stat().st_size / 1e6:.1f} MB, {len(site.parts)} parts, {len(site.pitches)} pitches, "
          f"{n} prop instances, parking {r.parking}, {time.time() - t:.1f}s", flush=True)
    return out


if __name__ == "__main__":
    argv = sys.argv[sys.argv.index("--") + 1:]
    main(Path(argv[0]), game="--game" in argv)
